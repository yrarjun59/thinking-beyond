/**
 * Extracts precise, per-episode tags from video metadata.
 * - Pulls from title, description, and guest name
 * - Filters out generic tags that appear in many videos
 * - Boosts guest names and specific topics
 * - Single configuration point: GENERIC_TAG_THRESHOLD
 *
 * @param {Object} video - Single video object from channel-videos.json
 * @param {Array} allVideos - All channel videos (for frequency counting)
 * @param {number} threshold - GENERIC_TAG_THRESHOLD config value
 * @returns {Array} Precise, filtered tags for this episode
 */
function extractPreciseTags(video, allVideos, threshold = GENERIC_TAG_THRESHOLD) {
  const tagCandidates = new Map();

  // Helper: add a tag with base weight, checking frequency against allVideos
  const addTag = (rawTag, baseWeight = 1) => {
    if (!rawTag) return;
    const cleaned = String(rawTag)
      .toLowerCase()
      .trim()
      .replace(/\s+/g, ' ')
      .replace(/["'“”‘’()[\]{}|\\/<>,.;:!?…–—-]+$/g, '')
      .replace(/^["'“”‘’()[\]{}|\\/<>,.;:!?…–—-]+/g, '')
      .trim();

    if (cleaned.length < 3 || cleaned.length > 40) return;
    if (STOPWORDS.has(cleaned)) return;

    // Check frequency of this tag across ALL videos (to filter generics)
    const freq = (() => {
      let count = 0;
      allVideos.forEach(v => {
        if (v.tags && v.tags.includes(cleaned)) count++;
      });
      return count;
    })();

    if (freq > threshold) return; // Generic tag appears in too many videos - skip

    tagCandidates.set(cleaned, (tagCandidates.get(cleaned) || 0) + baseWeight);
  };

  // 1. Extract from guest name (highest priority + weight boost)
  if (video.guest) {
    const guestLower = String(video.guest).toLowerCase().trim();
    addTag(guestLower, GUEST_NAME_WEIGHT); // Base guest tag (lowercase)
    addTag(video.guest, GUEST_NAME_WEIGHT); // Proper case guest name
    // Note: guest domain/field could be inferred from title later
  }

  // 2. Extract from title - pull specific nouns/terms
  if (video.title) {
    const title = video.title.toLowerCase();
    // Specific technology/topics (boosted) - these are episode-specific
    const specificTech = ['fintech', 'ai', 'machine learning', 'blockchain', 'crypto',
      'digital payment', 'startup', 'entrepreneur', 'saas', 'iot', 'cybersecurity'];
    for (const tech of specificTech) {
      if (title.includes(tech)) {
        addTag(tech, SPECIFIC_TOPIC_WEIGHT * 2); // Double boost for specific topics
      }
    }
    // If title doesn't contain "technology" or "tech" as a generic word, add it once
    if (!title.includes('technology') && !title.includes('tech')) {
      addTag('technology', 1);
    }

    // Extract capitalized phrases from title (potential proper nouns)
    const capitalizedPhrases = video.title
      .split(/\s+/)
      .filter(w => w.length > 2 && w[0] >= 'A' && w[0] <= 'Z')
      .slice(0, 5) // limit to top 5 capitalized phrases
      .join(' ');
    if (capitalizedPhrases.length > 3) {
      addTag(capitalizedPhrases, 1);
    }
  }

  // 3. Extract from description/summary - pull longer phrases
  if (video.description) {
    const desc = video.description.toLowerCase();
    // Pull 3-4 word phrases that might be specific entities, events, or topics
    const words = desc.split(/\s+/).filter(w => w.length > 2);
    // Generate overlapping 3-word phrases
    for (let i = 0; i < words.length - 2; i++) {
      const phrase = words.slice(i, i + 3).join(' ');
      if (phrase.length > 5 && !STOPWORDS.has(phrase)) {
        addTag(phrase, 1);
      }
    }
    // Also add a longer 4-word phrase if available
    if (words.length >= 4) {
      const phrase4 = words.slice(0, 4).join(' ');
      if (phrase4.length > 6 && !STOPWORDS.has(phrase4)) {
        addTag(phrase4, 1);
      }
    }
  }

  // 4. Also add any existing tags from the video, but de-weighted if they're generic
  if (video.tags && video.tags.length > 0) {
    video.tags.forEach(tag => {
      const lowerTag = String(tag).toLowerCase().trim();
      // Check frequency of this tag across all videos
      const freq = (() => {
        let count = 0;
        allVideos.forEach(v => {
          if (v.tags && v.tags.includes(lowerTag)) count++;
        });
        return count;
      })();
      if (freq <= threshold) {
        // Tag is specific enough (appears in <= threshold videos) - add with normal weight
        addTag(lowerTag, 1);
      }
      // If freq > threshold, tag is generic - intentionally skip it
    });
  }

  // 5. Filter to only tags that passed the frequency check
  const preciseTags = Array.from(tagCandidates.entries())
    .filter(([, weight]) => weight > 0)
    .sort((a, b) => b[1] - a[1]) // Sort by weight (descending - highest weight first)
    .map(([tag]) => tag); // Return just tag names

  return preciseTags;
}

// === Build the keyword set ===

const candidates = new Map();

// 1. Anchor phrases always lead the list (highest weight)
for (const anchor of config.seoAnchors || []) {
  const cleaned = String(anchor || '').toLowerCase().trim()
    .replace(/["'“”‘’()[\]{}|\\/<>,.;:!?…–—-]+$/g, '')
    .replace(/^["'“”‘’()[\]{}|\\/<>,.;:!?…–—-]+/g, '')
    .trim();
  if (cleaned.length >= 3) {
    candidates.set(cleaned, 100);
  }
}

// 2. Precise per-episode tags from the SEO window (latest 17 videos)
const seoVideos = videos.slice(0, SEO_VIDEO_COUNT);
for (const video of seoVideos) {
  const preciseTags = extractPreciseTags(video, videos, GENERIC_TAG_THRESHOLD);
  for (const tag of preciseTags) {
    const currentWeight = candidates.get(tag) || 0;
    candidates.set(tag, currentWeight + 5); // Base weight for precise tags from SEO window
  }
}

// 3. Frequent unigrams and bigrams from titles + descriptions of the SEO window
// (only add unique words that aren't already in candidates as precise tags)
const seoText = seoVideos.map(video => `${video.title} ${video.description || video.summary || ''}`).join(' \n ');
const words = seoText.toLowerCase()
  .replace(/https?:\/\/\S+/g, ' ')
  .replace(/[^a-z0-9\s]/g, ' ')
  .split(/\s+/)
  .filter(Boolean);

// Add unigrams (longer than 3 chars, not stopwords, not already in candidates)
for (const word of words) {
  if (word.length > 3 && !STOPWORDS.has(word) && !candidates.has(word)) {
    candidates.set(word, 1);
  }
}

// Add bigrams (pairs of adjacent words, both > 2 chars, not stopwords, not already in candidates)
for (let i = 0; i < words.length - 1; i++) {
  const w1 = words[i];
  const w2 = words[i + 1];
  if (w1.length > 2 && w2.length > 2 && !STOPWORDS.has(w1) && !STOPWORDS.has(w2)) {
    const bigram = `${w1} ${w2}`;
    if (!candidates.has(bigram)) {
      candidates.set(bigram, 1);
    }
  }
}

// 5. Nepal-adjacent compound topics get a boost so geo searches rank
// (only if they're already in candidates - they passed the precision filter earlier)
for (const keyword of [...candidates.keys()]) {
  if (/nepal/.test(keyword)) candidates.set(keyword, candidates.get(keyword) + 4);
  if (/podcast/.test(keyword)) candidates.set(keyword, candidates.get(keyword) + 2);
}

// 6. Final selection: sort by weight (descending), slice to 60 keywords
const keywords = [...candidates.entries()]
  .sort((a, b) => b[1] - a[1])
  .slice(0, 60)
  .map(([keyword]) => keyword);

// Write output to src/site-keywords.json
await writeFile(
  resolve(process.cwd(), 'src/site-keywords.json'),
  `${JSON.stringify(keywords, null, 2)}\n`
);
console.log(
  `Wrote ${keywords.length} precise keywords to src/site-keywords.json ` +
  `(anchors + precise per-episode tags (threshold=${GENERIC_TAG_THRESHOLD}, guests boosted=${GUEST_NAME_WEIGHT})).`
);