// Build src/site-keywords.json — the site's search/AI keyword set.
//
// Combines:
//   1. Anchor phrases from src/channel-config.json (brand + Nepal geo terms)
//   2. Precise, per-episode tags extracted from titles, descriptions, and guests
//      (generic/high-frequency tags are filtered out)
//
// Precision Configuration — one configuration point:
//
//   GENERIC_TAG_THRESHOLD: tags appearing in more than N videos are considered
//     generic and filtered out. Set to 3 means only tags unique to 1-3 videos remain.
//     Increase this number to keep more tags; decrease to make tag set more selective.
//
//   GUEST_NAME_WEIGHT: boost factor applied when a guest name is detected in tags.
//     Guest names are the most precise episode identifiers.
//
//   SPECIFIC_TOPIC_WEIGHT: boost factor for specific topics extracted from titles/
//     descriptions (e.g., "fintech", "AI") vs generic terms ("technology", "nepal").
//
// Consumers: index.html meta keywords, the Seo component, llms.txt, and the RSS
// feed. Regenerated by the daily workflow, so keywords follow real video topics.

import {readFile, writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';

const config = await readFile(new URL('../src/channel-config.json', import.meta.url), 'utf8').then(JSON.parse).catch(() => ({}));
const videos = JSON.parse(await readFile(new URL('../src/channel-videos.json', import.meta.url), 'utf8'));
const SEO_VIDEO_COUNT = Number(process.env.SEO_VIDEO_COUNT) || 17;

// === PRECISION CONFIGURATION (ONE POINT TO EDIT) ===
// Tags appearing more than this many videos are considered generic and filtered out.
const GENERIC_TAG_THRESHOLD = 3;
// Boost factor for guest names detected in tags (guest names = most precise identifier).
const GUEST_NAME_WEIGHT = 5;
// Boost factor for specific topics extracted from titles/descriptions (e.g., "fintech", "AI")
const SPECIFIC_TOPIC_WEIGHT = 2;

